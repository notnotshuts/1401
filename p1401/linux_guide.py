"""Russian Linux handoff, derived from the verified EFI rather than Windows UI steps."""
from . import guide

VALUES = {'Off': 'выключить', 'On': 'включить', 'On if you have it': 'включить, если доступно',
          '64M or more': '64 МБ или больше', 'Leave it Enabled': 'оставить включённым',
          'Leave it Disabled': 'оставить выключенным'}
REASONS = {'Secure Boot': 'Позволяет загрузить OpenCore с USB.', 'CSM': 'Нужен режим UEFI.',
           'Fast Boot': 'Прошивка должна обнаружить флешку.', 'Above 4G': 'Размещение памяти видеокарты.',
           'Resizable BAR': 'Параметр согласован с собранной EFI; после изменения пересоберите EFI.',
           'XHCI': 'Передача управления USB операционной системе.', 'CFG Lock': 'Управление питанием CPU.',
           'VT-d': 'Совместимость с обработкой IOMMU в этой EFI.',
           'DVMT': 'Память для встроенной графики Intel.', 'IOMMU': 'Совместимость загрузки на AMD.'}


def render(report, config, profile):
    settings = guide.bios_settings(report, config, profile.get('disabled_devices', {}))
    keys = guide.keys(report)
    board = report.get('Motherboard', {}).get('Name', 'неизвестна')
    macos = guide.macos_name(profile.get('macos_version', ''))
    lines = [f'1401 — установка {macos}', f'Плата: {board}',
             'Этот гайд относится к проверенной EFI и выбранному отчёту. Импортированный отчёт должен быть от целевого ПК.', '',
             '1. Подготовьте установку',
             'Сохраните важные файлы. Подготовьте отдельный диск для macOS и Ethernet: Wi-Fi в восстановлении может не работать.',
             'Если есть Windows, сохраните и проверьте ключ восстановления BitLocker перед изменением BIOS. Приложение не приостанавливает BitLocker.',
             'Если Windows загружается в Legacy или используется RAID/RST/VMD, сначала выполните документированную производителем миграцию. Не переключайте режим дисков вслепую.', '',
             '2. Создайте USB в приложении',
             'Откройте «Установочный USB», выберите флешку по модели и размеру, нажмите «Очистить и записать USB».',
             'Введите показанный путь /dev/… для подтверждения. Все данные именно на этой флешке будут удалены.',
             'Дождитесь успешной записи и проверки файлов. Apple Recovery загружается автоматически; для установки понадобится интернет.', '',
             '3. Настройте BIOS',
             'Сфотографируйте этот список перед перезагрузкой. Сверьте названия и доступность пунктов с инструкцией к своей плате.',
             f'Клавиша входа: {keys[0] if keys else "по инструкции к ПК (часто Del или F2)"}.',
             'Значения ниже получены из вашего отчёта и config.plist. TPM/PTT менять не нужно.']
    for setting in settings:
        value = VALUES.get(setting.want, setting.want)
        reason = next((text for prefix, text in REASONS.items() if setting.name.startswith(prefix)), '')
        lines.append(f'• {setting.name}: {value}. {"Обязательно" if setting.required else "Рекомендуется"}. {reason}')
        if setting.name.startswith('CFG Lock') and not setting.required:
            lines.append('  Если пункт скрыт, пропустите: EFI уже содержит обход CFG Lock.')
        elif setting.required:
            lines.append('  Если пункт недоступен, проверьте инструкцию к плате и условия загрузки до продолжения.')
    disabled = profile.get('disabled_devices', {})
    if disabled:
        lines += ['', 'Отключённые устройства в EFI: ' + str(disabled), 'Подключите монитор и сеть к поддерживаемым устройствам.']
    lines += ['', '4. Загрузитесь с флешки',
              f'Меню загрузки: {keys[1] if keys else "по инструкции к ПК (часто F12, F11 или Esc)"}. Выберите USB с пометкой UEFI.',
              'В меню OpenCore выберите Apple Recovery / установщик (запись с .dmg).', '',
              '5. Установите macOS',
              'В Дисковой утилите включите «Вид → Показать все устройства». Выберите только отдельный диск, подготовленный для macOS.',
              'Очистите его: имя Macintosh HD, формат APFS, схема GUID. Очистка удалит все данные выбранного диска.',
              'Закройте Дисковую утилиту, выберите установку macOS на Macintosh HD.',
              'После перезагрузок снова загружайте USB: выбирайте macOS Installer, затем Macintosh HD.',
              'Сохраните флешку: пока она нужна для запуска. Перенос EFI на внутренний диск — отдельный шаг после проверки загрузки.', '',
              'Если возникла проблема',
              'USB не видно: проверьте UEFI, другой USB-порт и Fast Boot.',
              'Диск не видно: проверьте поддерживаемый контроллер, VMD/RAID и свежий отчёт; не меняйте режим хранения без подготовки существующей ОС.',
              'Чёрный экран: проверьте карту, выход монитора, отключённые устройства и требования драйвера NVIDIA / OCLP.',
              'Ошибка в приложении: откройте «Журнал», сохраните его и build-result.json. После изменения железа или BIOS повторите сканирование.', '',
              'Подробности настроек из движка (английский):']
    lines.extend(guide.setting_line(setting) for setting in settings)
    return '\n'.join(lines) + '\n'
